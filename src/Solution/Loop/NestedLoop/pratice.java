package Solution.Loop.NestedLoop;
import java.util.Scanner;
public class pratice {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);
        int n = sc.nextInt();
        for(int i=1;i<=n;i++){
            for(int j=1;j<=3;j++){
                System.out.println("Ritik");
            }
            System.out.println();
        }
    }
}
